function initGalleryLightbox(){
  const items = Array.from(document.querySelectorAll("[data-gallery-item]"));
  if(!items.length) return;

  const lightbox = document.getElementById("lightbox");
  const img = document.getElementById("lightboxImg");
  const counter = document.getElementById("lightboxCounter");
  const btnClose = document.getElementById("lightboxClose");
  const btnPrev = document.getElementById("lightboxPrev");
  const btnNext = document.getElementById("lightboxNext");

  let index = 0;
  let lastFocused = null;

  function pad(n){ return String(n).padStart(2,"0"); }

  function render(){
    img.classList.remove("show");
    const src = items[index].dataset.full;
    const swap = new Image();
    swap.onload = () => {
      img.src = src;
      requestAnimationFrame(()=> img.classList.add("show"));
    };
    swap.src = src;
    counter.textContent = `${pad(index+1)} / ${pad(items.length)}`;
  }

  function open(i){
    index = i;
    lastFocused = document.activeElement;
    lightbox.classList.add("open");
    requestAnimationFrame(()=> lightbox.classList.add("show"));
    lightbox.setAttribute("aria-hidden","false");
    document.body.style.overflow = "hidden";
    render();
    btnClose.focus();
  }

  function close(){
    lightbox.classList.remove("show");
    lightbox.setAttribute("aria-hidden","true");
    document.body.style.overflow = "";
    setTimeout(()=> lightbox.classList.remove("open"), 300);
    if(lastFocused) lastFocused.focus();
  }

  function next(){
    const rtl = document.body.classList.contains("rtl");
    index = rtl ? (index - 1 + items.length) % items.length : (index + 1) % items.length;
    render();
  }
  function prev(){
    const rtl = document.body.classList.contains("rtl");
    index = rtl ? (index + 1) % items.length : (index - 1 + items.length) % items.length;
    render();
  }

  items.forEach((el,i)=> el.addEventListener("click", ()=> open(i)));
  btnClose.addEventListener("click", close);
  btnNext.addEventListener("click", next);
  btnPrev.addEventListener("click", prev);

  lightbox.addEventListener("click", (e)=>{
    if(e.target === lightbox) close();
  });

  document.addEventListener("keydown",(e)=>{
    if(!lightbox.classList.contains("open")) return;
    if(e.key === "Escape") close();
    if(e.key === "ArrowRight") next();
    if(e.key === "ArrowLeft") prev();
  });

  // Swipe support
  let touchStartX = 0;
  let touchDeltaX = 0;
  lightbox.addEventListener("touchstart",(e)=>{
    touchStartX = e.touches[0].clientX;
    touchDeltaX = 0;
  },{passive:true});
  lightbox.addEventListener("touchmove",(e)=>{
    touchDeltaX = e.touches[0].clientX - touchStartX;
  },{passive:true});
  lightbox.addEventListener("touchend",()=>{
    if(Math.abs(touchDeltaX) > 40){
      touchDeltaX < 0 ? next() : prev();
    }
  });
}
