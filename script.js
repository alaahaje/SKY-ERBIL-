let currentLang = localStorage.getItem("skyLang") || "en";
const langOrder = ["EN","AR","KU"];

function applyLanguage(lang){
  currentLang = lang;
  localStorage.setItem("skyLang", lang);
  const dict = translations[lang];
  document.documentElement.lang = lang;
  document.body.classList.toggle("rtl", lang !== "en");
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.dataset.i18n;
    if(dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.getElementById("langBtn").textContent = lang.toUpperCase();
  updateHoursStatus();
}

/* Live open/closed status for the Working Hours section (Erbil local time) */
function getErbilMinutes(){
  const parts = new Intl.DateTimeFormat("en-GB",{
    timeZone:"Asia/Baghdad", hour:"2-digit", minute:"2-digit", hour12:false
  }).formatToParts(new Date());
  const h = parseInt(parts.find(p=>p.type==="hour").value,10);
  const m = parseInt(parts.find(p=>p.type==="minute").value,10);
  return h*60+m;
}

function updateHoursStatus(){
  const rows = document.querySelectorAll(".hours-row");
  if(!rows.length) return;
  const nowMin = getErbilMinutes();
  const dict = translations[currentLang] || translations.en;
  rows.forEach(row=>{
    let isOpen;
    if(row.dataset.always === "true"){
      isOpen = true;
    } else {
      const open = parseInt(row.dataset.open,10);
      const close = parseInt(row.dataset.close,10);
      isOpen = nowMin >= open && nowMin < close;
    }
    const badge = row.querySelector("[data-hours-badge]");
    const dot = row.querySelector("[data-hours-dot]");
    const label = row.querySelector("[data-hours-label]");
    badge.classList.toggle("open", isOpen);
    badge.classList.toggle("closed", !isOpen);
    dot.classList.toggle("green", isOpen);
    dot.classList.toggle("red", !isOpen);
    label.textContent = isOpen ? (dict["hours.openNow"] || "Open Now") : (dict["hours.closedNow"] || "Closed Now");
  });
}

